const DICTS: Record<Locale, Dict> = { en, hi, bn, ta, mr };

/**
 * Translation lookup. Falls back to English for any key a language has not covered yet,
 * so adding a partial translation never leaves blanks on screen.
 */
export function translate(locale: Locale, key: string, vars: Record<string, string | number> = {}): string {
  const value = DICTS[locale]?.[key] ?? en[key] ?? key;
  return Object.entries(vars).reduce(
    (acc, [k, v]) => acc.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v)),
    value,
  );
}
